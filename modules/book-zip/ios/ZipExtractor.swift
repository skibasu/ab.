import Foundation
import ZIPFoundation

// Statuses cross the bridge; user-facing messages remain in the TypeScript constants.
enum ZipFailure: String, Error {
  case invalid, cancelled, limit, noSpace
}

struct CheckedZipEntry {
  let size: UInt64
  let checksum: UInt32
  let directory: Bool
  let output: String?
}

final class ZipCancellation: @unchecked Sendable {
  private let lock = NSLock()
  private var cancelled = false

  func cancel() {
    lock.lock()
    cancelled = true
    lock.unlock()
  }

  func check() throws {
    lock.lock()
    let value = cancelled
    lock.unlock()
    if value { throw ZipFailure.cancelled }
  }
}

// No archive path is ever used as an output path. All output names are generated by the app.
func extractBookZip(
  archiveURL: URL, destination: URL, expected: [CheckedZipEntry],
  maxBytes: UInt64, chunkBytes: Int, cancellation: ZipCancellation
) throws {
  try cancellation.check()
  let archive = try Archive(url: archiveURL, accessMode: .read)
  var index = 0
  var total: UInt64 = 0
  for entry in archive {
    try cancellation.check()
    guard index < expected.count else { throw ZipFailure.invalid }
    let checked = expected[index]
    index += 1
    guard entry.type != .symlink,
          (entry.type == .directory) == checked.directory,
          entry.uncompressedSize == checked.size,
          checked.directory || entry.checksum == checked.checksum else { throw ZipFailure.invalid }
    if checked.directory { continue }
    var handle: FileHandle?
    if let name = checked.output {
      guard UUID(uuidString: String(name.dropLast(4))) != nil, name.hasSuffix(".mp3") else {
        throw ZipFailure.invalid
      }
      let url = destination.appendingPathComponent(name)
      // Exclusive creation also prevents a destination symlink from being followed.
      let descriptor = open(url.path, O_WRONLY | O_CREAT | O_EXCL, S_IRUSR | S_IWUSR)
      guard descriptor >= 0 else {
        if errno == ENOSPC { throw ZipFailure.noSpace }
        throw ZipFailure.invalid
      }
      handle = FileHandle(fileDescriptor: descriptor, closeOnDealloc: true)
    }
    defer { try? handle?.close() }
    var written: UInt64 = 0
    let checksum = try archive.extract(entry, bufferSize: chunkBytes, skipCRC32: false) { data in
      try cancellation.check()
      written += UInt64(data.count)
      total += UInt64(data.count)
      guard total <= maxBytes else { throw ZipFailure.limit }
      guard written <= checked.size else { throw ZipFailure.invalid }
      do {
        try handle?.write(contentsOf: data)
      } catch {
        let nsError = error as NSError
        if nsError.code == NSFileWriteOutOfSpaceError ||
            (nsError.domain == NSPOSIXErrorDomain && nsError.code == Int(ENOSPC)) {
          throw ZipFailure.noSpace
        }
        throw error
      }
    }
    guard written == checked.size, checksum == checked.checksum else { throw ZipFailure.invalid }
  }
  guard index == expected.count else { throw ZipFailure.invalid }
  try cancellation.check()
}
